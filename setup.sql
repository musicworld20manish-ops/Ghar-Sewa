create or replace function public.find_nearby_providers(
  p_service_id bigint,p_lat double precision,p_lng double precision,p_radius_km double precision default 25
)
returns table(provider_id uuid,full_name text,phone text,address text,experience_years integer,rating_avg numeric,verification_status text,distance_km double precision)
language sql stable security definer set search_path=public
as $$
select p.id,p.full_name,p.phone,p.address,p.experience_years,p.rating_avg,p.verification_status,
round((6371 * acos(least(1,greatest(-1,
cos(radians(p_lat))*cos(radians(p.latitude))*cos(radians(p.longitude)-radians(p_lng))
+sin(radians(p_lat))*sin(radians(p.latitude))
))))::numeric,2)::double precision
from public.profiles p
join public.provider_services ps on ps.provider_id=p.id
where p.role='provider' and p.verification_status='approved' and ps.service_id=p_service_id
and p.latitude is not null and p.longitude is not null
and (6371 * acos(least(1,greatest(-1,
cos(radians(p_lat))*cos(radians(p.latitude))*cos(radians(p.longitude)-radians(p_lng))
+sin(radians(p_lat))*sin(radians(p.latitude))
)))) <= p_radius_km
order by distance_km asc;
$$;

