drop policy if exists "public read active services" on public.services;
create policy "public read active services" on public.services for select using (active=true);

drop policy if exists "users read own profile" on public.profiles;
create policy "users read own profile" on public.profiles for select to authenticated using (auth.uid()=id);

drop policy if exists "users insert own profile" on public.profiles;
create policy "users insert own profile" on public.profiles for insert to authenticated with check (auth.uid()=id);

drop policy if exists "users update own profile" on public.profiles;
create policy "users update own profile" on public.profiles for update to authenticated using (auth.uid()=id) with check (auth.uid()=id);

drop policy if exists "providers read own expertise" on public.provider_services;
create policy "providers read own expertise" on public.provider_services for select to authenticated using (provider_id=auth.uid());

drop policy if exists "providers add own expertise" on public.provider_services;
create policy "providers add own expertise" on public.provider_services for insert to authenticated with check (provider_id=auth.uid());

